import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = new URL("../design/tokens.json", import.meta.url);
const TARGET = new URL("../src/ui/styles/tokens.css", import.meta.url);

// Keys that carry documentation or metadata, not values.
const SKIP = new Set(["meta", "version", "name", "themes", "note", "usage", "sample"]);
// Wrapper keys that only group entries; their children join the parent path.
const TRANSPARENT = new Set(["tokens", "groups", "styles", "value"]);
const THEME_KEYS = new Set(["light", "dark"]);

const source = JSON.parse(readFileSync(SOURCE, "utf8"));
const families = source.type?.families ?? {};

// Font families served by next/font. The app defines these variables on <html>.
const FONT_VARIABLES = {
  Inter: "--font-inter",
  "Alte Haas Grotesk": "--font-alte-haas-grotesk",
};

// Points a font stack at its next/font variable, keeping the fallbacks after it.
function withFontVariable(stack) {
  const match = /^"([^"]+)",\s*(.+)$/.exec(stack);
  const variable = match ? FONT_VARIABLES[match[1]] : undefined;
  return variable ? `var(${variable}), ${match[2]}` : stack;
}

for (const key of Object.keys(families)) {
  families[key] = withFontVariable(families[key]);
}

const toKebab = (raw) =>
  String(raw)
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .toLowerCase()
    .replace(/^-+|-+$/g, "");

// Adds a path segment. A repeated segment ("display" > "display") or one that
// already starts with the parent ("radius" > "radius-md") replaces the parent.
function push(segments, raw) {
  const seg = toKebab(raw);
  if (!seg) return segments;
  const last = segments[segments.length - 1];
  if (last !== undefined && (seg === last || seg.startsWith(`${last}-`))) {
    return [...segments.slice(0, -1), seg];
  }
  return [...segments, seg];
}

const isPrimitive = (v) => typeof v === "string" || typeof v === "number";

function isThemePair(node) {
  if (!node || typeof node !== "object" || Array.isArray(node)) return false;
  const keys = Object.keys(node);
  return keys.length > 0 && keys.every((k) => THEME_KEYS.has(k) && isPrimitive(node[k]));
}

function visit(node, segments, out) {
  if (isThemePair(node)) {
    out.push({
      name: segments.join("-"),
      light: String(node.light ?? node.dark),
      dark: node.dark === undefined ? undefined : String(node.dark),
    });
    return;
  }
  if (isPrimitive(node)) {
    out.push({ name: segments.join("-"), light: String(node) });
    return;
  }
  if (Array.isArray(node)) {
    node.forEach((item, index) => {
      const named = item && typeof item === "object" && typeof item.name === "string";
      visit(item, push(segments, named ? item.name : String(index)), out);
    });
    return;
  }
  if (node && typeof node === "object") {
    for (const [key, child] of Object.entries(node)) {
      if (SKIP.has(key)) continue;
      if (TRANSPARENT.has(key)) {
        visit(child, segments, out);
        continue;
      }
      let value = child;
      if (key === "family" && typeof child === "string" && families[child] !== undefined) {
        value = `var(--type-families-${toKebab(child)})`;
      }
      visit(value, push(segments, key), out);
    }
  }
}

const entries = [];
visit(source, [], entries);

const seen = new Set();
for (const e of entries) {
  if (seen.has(e.name)) throw new Error(`Duplicate token name: --${e.name}`);
  seen.add(e.name);
}

const lightLines = entries.map((e) => `  --${e.name}: ${e.light};`);
const darkEntries = entries.filter((e) => e.dark !== undefined);
const darkLines = darkEntries.map((e) => `    --${e.name}: ${e.dark};`);

const out = [
  "/* Generated by scripts/build-tokens.mjs. Do not edit. */",
  ":root {",
  ...lightLines,
  "}",
];

if (darkLines.length > 0) {
  out.push(
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    ...darkLines,
    "  }",
    "}",
    "",
    ':root[data-theme="dark"] {',
    ...darkLines,
    "}",
  );
}

const target = fileURLToPath(TARGET);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${out.join("\n")}\n`);

console.log(
  `Wrote ${entries.length} variables (${darkEntries.length} with dark values) to ${target}`,
);
